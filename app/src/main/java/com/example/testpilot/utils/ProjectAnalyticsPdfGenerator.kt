
package com.example.testpilot.utils

import android.content.Context
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.RectF
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.net.Uri
import com.example.testpilot.data.local.DefectEntity
import com.example.testpilot.data.local.ProjectEntity
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ProjectAnalyticsPdfGenerator {

    private data class ChartItem(
        val label: String,
        val value: Int,
        val color: Int
    )

    fun generate(
        context: Context,
        uri: Uri,
        project: ProjectEntity,
        totalTestCases: Int,
        totalExecutions: Int,
        passedExecutions: Int,
        failedExecutions: Int,
        blockedExecutions: Int,
        inProgressExecutions: Int,
        notRunExecutions: Int,
        passRate: Float,
        totalSteps: Int,
        passedSteps: Int,
        failedSteps: Int,
        blockedSteps: Int,
        notRunSteps: Int,
        defects: List<DefectEntity>
    ) {
        val document = PdfDocument()

        val pageWidth = 595
        val pageHeight = 842
        val left = 45f
        val right = 550f

        val titlePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(70, 55, 130)
            textSize = 25f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        val headingPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(70, 55, 130)
            textSize = 16f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        val bodyPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.DKGRAY
            textSize = 11f
        }

        val boldPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.BLACK
            textSize = 11f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        val smallPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.GRAY
            textSize = 9f
        }

        var pageNumber = 0
        var page: PdfDocument.Page? = null
        var canvas: Canvas? = null
        var y = 0f

        fun startPage() {
            pageNumber++

            val info = PdfDocument.PageInfo.Builder(
                pageWidth,
                pageHeight,
                pageNumber
            ).create()

            page = document.startPage(info)
            canvas = page!!.canvas
            y = 55f

            canvas!!.drawText("TestPilot", left, y, headingPaint)
            canvas!!.drawText(
                "PROJECT QUALITY REPORT",
                left,
                y + 25f,
                titlePaint
            )

            y += 45f

            canvas!!.drawLine(left, y, right, y, bodyPaint)
            y += 25f
        }

        fun finishPage() {
            if (page != null) {
                canvas?.drawText(
                    "Generated by TestPilot | Page $pageNumber",
                    left,
                    815f,
                    smallPaint
                )

                document.finishPage(page!!)
                page = null
                canvas = null
            }
        }

        fun ensureSpace(required: Float = 30f) {
            if (y + required > 790f) {
                finishPage()
                startPage()
            }
        }

        fun drawLine(text: String, paint: Paint = bodyPaint) {
            ensureSpace()
            canvas!!.drawText(text, left, y, paint)
            y += 20f
        }

        fun drawSection(title: String) {
            ensureSpace(45f)
            y += 8f
            canvas!!.drawText(title, left, y, headingPaint)
            y += 25f
        }

        fun drawPieChart(
            title: String,
            items: List<ChartItem>,
            centerX: Float,
            centerY: Float,
            radius: Float
        ) {
            canvas!!.drawText(
                title,
                left,
                centerY - radius - 18f,
                headingPaint
            )

            val total = items.sumOf { it.value }

            if (total == 0) {
                val noDataPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                    color = Color.GRAY
                    textSize = 12f
                }

                canvas!!.drawText(
                    "No data available",
                    centerX - radius,
                    centerY + 5f,
                    noDataPaint
                )
                return
            }

            var startAngle = -90f

            val rect = RectF(
                centerX - radius,
                centerY - radius,
                centerX + radius,
                centerY + radius
            )

            items.forEach { item ->
                if (item.value > 0) {
                    val sweepAngle =
                        item.value.toFloat() / total * 360f

                    val piePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                        color = item.color
                        style = Paint.Style.FILL
                    }

                    canvas!!.drawArc(
                        rect,
                        startAngle,
                        sweepAngle,
                        true,
                        piePaint
                    )

                    startAngle += sweepAngle
                }
            }

            val legendPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                color = Color.DKGRAY
                textSize = 10f
            }

            val legendX = centerX + radius + 35f
            var legendY = centerY - 25f

            items.forEach { item ->
                val squarePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                    color = item.color
                    style = Paint.Style.FILL
                }

                canvas!!.drawRect(
                    legendX,
                    legendY - 9f,
                    legendX + 10f,
                    legendY + 1f,
                    squarePaint
                )

                val percentage =
                    item.value.toFloat() / total * 100f

                canvas!!.drawText(
                    "${item.label}: ${item.value} (${String.format("%.1f", percentage)}%)",
                    legendX + 17f,
                    legendY,
                    legendPaint
                )

                legendY += 20f
            }

            val totalPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                color = Color.BLACK
                textSize = 10f
                typeface = Typeface.DEFAULT_BOLD
            }

            canvas!!.drawText(
                "Total: $total",
                legendX + 17f,
                legendY + 3f,
                totalPaint
            )
        }

        fun drawStepDistribution() {
            val items = listOf(
                ChartItem("Passed", passedSteps, Color.rgb(53, 201, 138)),
                ChartItem("Failed", failedSteps, Color.rgb(255, 92, 108)),
                ChartItem("Blocked", blockedSteps, Color.rgb(255, 181, 71)),
                ChartItem("Not Run", notRunSteps, Color.rgb(121, 134, 203))
            )

            val total = items.sumOf { it.value }

            canvas!!.drawText(
                "Test Step Results",
                left,
                730f,
                headingPaint
            )

            val barX = left
            val barY = 748f
            val barWidth = 500f
            val barHeight = 16f

            if (total == 0) {
                canvas!!.drawText(
                    "No test step data available",
                    left,
                    780f,
                    bodyPaint
                )
                return
            }

            var currentX = barX

            items.forEach { item ->
                if (item.value > 0) {
                    val segmentWidth =
                        item.value.toFloat() / total * barWidth

                    val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                        color = item.color
                        style = Paint.Style.FILL
                    }

                    canvas!!.drawRect(
                        currentX,
                        barY,
                        currentX + segmentWidth,
                        barY + barHeight,
                        paint
                    )

                    currentX += segmentWidth
                }
            }

            var legendY = 785f
            var legendX = left

            items.forEach { item ->
                val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                    color = item.color
                }

                canvas!!.drawRect(
                    legendX,
                    legendY - 9f,
                    legendX + 9f,
                    legendY,
                    paint
                )

                canvas!!.drawText(
                    "${item.label}: ${item.value}",
                    legendX + 13f,
                    legendY,
                    smallPaint
                )

                legendX += 125f
            }
        }

        try {
            // PAGE 1: WRITTEN PROJECT REPORT

            startPage()

            drawLine(
                "Project: ${project.projectName}",
                boldPaint
            )

            drawLine("Application: ${project.applicationName}")
            drawLine("Version: ${project.version}")
            drawLine("Status: ${project.status}")

            if (project.description.isNotBlank()) {
                drawLine("Description: ${project.description}")
            }

            val generatedDate = SimpleDateFormat(
                "dd MMM yyyy, HH:mm",
                Locale.getDefault()
            ).format(Date())

            drawLine("Generated: $generatedDate")

            drawSection("1. PROJECT OVERVIEW")

            drawLine("Total Test Cases: $totalTestCases")
            drawLine("Total Executions: $totalExecutions")
            drawLine("Total Defects: ${defects.size}")
            drawLine("Overall Pass Rate: ${"%.1f".format(passRate)}%")

            drawSection("2. TEST EXECUTION RESULTS")

            drawLine("Passed Executions: $passedExecutions")
            drawLine("Failed Executions: $failedExecutions")
            drawLine("Blocked Executions: $blockedExecutions")
            drawLine("In Progress Executions: $inProgressExecutions")
            drawLine("Not Run Executions: $notRunExecutions")

            drawSection("3. TEST STEP RESULTS")

            drawLine("Total Test Steps: $totalSteps")
            drawLine("Passed Steps: $passedSteps")
            drawLine("Failed Steps: $failedSteps")
            drawLine("Blocked Steps: $blockedSteps")
            drawLine("Not Run Steps: $notRunSteps")

            drawSection("4. DEFECT STATUS")

            drawLine("Open Defects: ${defects.count { it.status == "Open" }}")
            drawLine("In Progress: ${defects.count { it.status == "In Progress" }}")
            drawLine("Resolved: ${defects.count { it.status == "Resolved" }}")
            drawLine("Closed: ${defects.count { it.status == "Closed" }}")

            drawSection("5. DEFECT SEVERITY")

            drawLine("Critical: ${defects.count { it.severity == "Critical" }}")
            drawLine("High: ${defects.count { it.severity == "High" }}")
            drawLine("Medium: ${defects.count { it.severity == "Medium" }}")
            drawLine("Low: ${defects.count { it.severity == "Low" }}")

            finishPage()

            // PAGE 2: VISUAL ANALYTICS

            startPage()

            drawPieChart(
                title = "Execution Status",
                items = listOf(
                    ChartItem("Passed", passedExecutions, Color.rgb(53, 201, 138)),
                    ChartItem("Failed", failedExecutions, Color.rgb(255, 92, 108)),
                    ChartItem("Blocked", blockedExecutions, Color.rgb(255, 181, 71)),
                    ChartItem("In Progress", inProgressExecutions, Color.rgb(121, 134, 203)),
                    ChartItem("Not Run", notRunExecutions, Color.rgb(160, 160, 160))
                ),
                centerX = 120f,
                centerY = 190f,
                radius = 55f
            )

            drawPieChart(
                title = "Defect Status",
                items = listOf(
                    ChartItem("Open", defects.count { it.status == "Open" }, Color.rgb(255, 92, 108)),
                    ChartItem("In Progress", defects.count { it.status == "In Progress" }, Color.rgb(255, 181, 71)),
                    ChartItem("Resolved", defects.count { it.status == "Resolved" }, Color.rgb(53, 201, 138)),
                    ChartItem("Closed", defects.count { it.status == "Closed" }, Color.rgb(121, 134, 203))
                ),
                centerX = 120f,
                centerY = 385f,
                radius = 55f
            )

            drawPieChart(
                title = "Defect Severity",
                items = listOf(
                    ChartItem("Critical", defects.count { it.severity == "Critical" }, Color.rgb(255, 59, 79)),
                    ChartItem("High", defects.count { it.severity == "High" }, Color.rgb(255, 138, 69)),
                    ChartItem("Medium", defects.count { it.severity == "Medium" }, Color.rgb(255, 200, 87)),
                    ChartItem("Low", defects.count { it.severity == "Low" }, Color.rgb(53, 201, 138))
                ),
                centerX = 120f,
                centerY = 580f,
                radius = 55f
            )

            drawStepDistribution()

            finishPage()

            // PAGE 3: INDIVIDUAL REPORTED DEFECTS

            if (defects.isNotEmpty()) {
                startPage()

                drawSection("6. REPORTED DEFECTS")

                defects.forEachIndexed { index, defect ->
                    ensureSpace(90f)

                    drawLine("${index + 1}. ${defect.title}", boldPaint)
                    drawLine("Severity: ${defect.severity}")
                    drawLine("Status: ${defect.status}")

                    y += 8f
                }

                finishPage()
            }

            context.contentResolver.openOutputStream(uri)?.use { output ->
                document.writeTo(output)
            } ?: throw IllegalStateException(
                "Unable to open the selected file location."
            )

        } finally {
            document.close()
        }
    }
}
